function norm(s) { return String(s||"").replace(/[\u064B-\u0652]/g,"").replace(/[أإآ]/g,"ا").replace(/ة/g,"ه").replace(/ال/g,""); }

export function findHealthAnswer(text) {
  const nt = norm(text);
  let best = null, bestLen = 0;
  for (const qa of HEALTH_QA) {
    for (const k of qa.keys) {
      if (nt.includes(norm(k)) && k.length > bestLen) { best = qa.answer; bestLen = k.length; }
    }
  }
  return best;
}
