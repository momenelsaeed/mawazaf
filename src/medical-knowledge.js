// تصنيف 3 مستويات — Safety Layer قبل أي LLM:
// EMERGENCY → طوارئ فوراً | URGENT → بشري سريع | NORMAL → استقبال عادي
export function classifyUrgency(text) {
  const nt = normK(text);
  if (RED_FLAGS.some(w => nt.includes(normK(w)))) return "EMERGENCY";
  if (URGENT_FLAGS.some(w => nt.includes(normK(w)))) return "URGENT";
  return "NORMAL";
}

export function detectSpecialty(text) {
  const nt = normK(text);
  for (const [name, s] of Object.entries(SPECIALTIES)) {
    if (s.keys.some(k => nt.includes(normK(k)))) return name;
  }
  return null;
}

export function detectSymptomQuestion(specialty) {
  return SPECIALTIES[specialty]?.ask || null;
}

export function isEmergency(text) {
  const nt = normK(text);
  return RED_FLAGS.some(w => nt.includes(normK(w)));
}
